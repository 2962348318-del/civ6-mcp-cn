"""高玩知识库 —— 人类社区数千小时经验的可查询压缩(2026-08-09)。

## 定位与边界

strategy_space 存**文明特定**原理(军团窗口/汉萨结构),civ_kit 从 gamedata
推导**本文明硬事实**,boost_planner 等模块管**机器可查的数值**。本库补的是
第四类:**文明无关的通用判断力** —— 人类高手换任何文明都带着走的那套
"什么回合该有几座城、看见蛮族侦察兵先杀谁、什么时候能宣战"。

这类知识的特点是**判断性**:gamedata 里查不到"T60 该有 4 座城",它来自
社区(CivFanatics 攻略/速通玩家实践)的统计共识。所以本库的诚实机制不是
strategy_space 那套 source 机验(没得验),而是:
    1. 每条标 confidence(确定/推荐/可选/冒险 —— 与 advice 同词汇表);
    2. 每条标 source 类型:规则机制(可实机验证)/社区共识(统计经验)/
       本机实证(往局校准中验证过);
    3. 数值拿不准就写区间,不编精确数。

## 规则集口径

本机是**原版规则集**(Difficulties 表 8 档、无忠诚度/时代得分/总督表)。
所有条目按原版写;资料片才有的机制一律不收,免得模型照着不存在的机制打。
关键差异点已显式写进条目(如原版尤里卡是 50%,资料片才是 40%)。

## 消费方式

    · MCP 工具 get_expert_playbook(topic, turn) —— 按主题/回合查完整条目
    · end_turn 的 20 回合例行审视注入 phase_headline(turn) 一行阶段提醒
    · 条目 rule 写的是推导链而非口令 —— 与 strategy_space 同一设计哲学:
      LLM 读完能接着往下推,而不是背结论
"""

