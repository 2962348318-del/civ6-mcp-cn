def phase_headline(turn: int) -> str:
    """当前阶段的一行提醒 + 入口指引。找不到阶段返回空串。"""
    for lo, hi, text in _PHASE_HEADLINES:
        if lo <= turn <= hi:
            return f"📖 {text}(详见 get_expert_playbook)"
    return ""


def self_check() -> list[str]:
    """数据自检:id 唯一、词汇表合法、回合窗口有序。供测试调用。"""
    problems: list[str] = []
    seen: set[str] = set()
    for e in ENTRIES:
        if e.id in seen:
            problems.append(f"重复 id:{e.id}")
        seen.add(e.id)
        if e.topic not in TOPICS:
            problems.append(f"{e.id}:未知主题 {e.topic}")
        if e.confidence not in _CONFIDENCE:
            problems.append(f"{e.id}:非法置信度 {e.confidence}")
        if e.source not in _SOURCES:
            problems.append(f"{e.id}:非法来源 {e.source}")
        if not (0 < e.phase[0] <= e.phase[1]):
            problems.append(f"{e.id}:回合窗口无效 {e.phase}")
    return problems
