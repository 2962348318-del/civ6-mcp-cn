def select_briefing(
    era: str | None,
    flags: set[str] | None = None,
    max_situational: int = 3,
) -> str:
    """组装本回合要注入的规则简报。

    Args:
        era: 当前时代的 EraType,如 "ERA_ANCIENT"。未知时只给恒定规则。
        flags: 局势标记,取自 _SITUATIONAL 的键。
        max_situational: 最多附加几条局势规则,防止刷屏(方案 §13.3)。

    Returns:
        可直接拼进回合报告的文本;没有内容时返回空串。
    """
    blocks = [_ALWAYS]

    if era and era in _ERA_RULES:
        blocks.append(_ERA_RULES[era])

    if flags:
        # 固定顺序,保证输出稳定可预期
        for key in ("civilian_exposed", "lost_contact", "threat_near", "at_war"):
            if key in flags and max_situational > 0:
                blocks.append(_SITUATIONAL[key])
                max_situational -= 1

    if not blocks:
        return ""
    body = "\n".join(blocks)
    return f"== 本回合规则提醒 ==\n{body}"


def flags_from_events(events: list) -> set[str]:
    """从回合事件里推导局势标记。

    只读 event.message 的文本特征 —— 这些字符串由 end_turn.py 生成,
    格式变了这里会静默失效,所以只做"锦上添花"的提示,不承担拦截职责。
    真正的拦截在 safety.py,那里读的是结构化数据。
    """
    flags: set[str] = set()
    for e in events:
        msg = getattr(e, "message", "") or ""
        if "THREAT:" in msg:
            flags.add("threat_near")
        if "LOST CONTACT" in msg or "VANISHED" in msg:
            flags.add("lost_contact")
        if "declared war" in msg.lower() or "AT WAR" in msg:
            flags.add("at_war")
    return flags
